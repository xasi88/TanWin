// Буквы, пройденные к уроку (включая его самого): из них складываются слоги и слова в этапе «Алфавит».
export function knownLetters(lessonId) {
  const out = [];
  for (const l of UNITS[1].lessons) {
    if (Array.isArray(l.letters)) out.push(...l.letters);
    if (l.id === lessonId) return [...new Set(out)];
  }
  return null; // после алфавита известны все буквы
}

