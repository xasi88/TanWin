export const byId = Object.fromEntries(LETTERS.map((l) => [l.id, l]));
export const byChar = Object.fromEntries(LETTERS.map((l) => [l.ch, l]));
Object.assign(byChar, { "أ": byId.hamza, "إ": byId.hamza, "ؤ": byId.hamza, "ئ": byId.hamza, "ٱ": byId.alif, "ى": byId.ya, "ة": byId.ta });

// Формы буквы: с помощью «соединителя нулевой ширины» (ZWJ) браузер рисует начальную/серединную/конечную форму
const ZWJ = "‍";
export function forms(l) {
  if (l.id === "hamza") return { iso: l.ch, ini: l.ch, med: l.ch, fin: l.ch };
  return l.nc
    ? { iso: l.ch, ini: l.ch, med: ZWJ + l.ch, fin: ZWJ + l.ch }
    : { iso: l.ch, ini: l.ch + ZWJ, med: ZWJ + l.ch + ZWJ, fin: ZWJ + l.ch };
}

