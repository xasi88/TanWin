/** Ссылка на WhatsApp с готовым текстом (или null, если номер не указан). */
export function feedbackLink(extra = "") {
  const phone = CONTACT.whatsapp.replace(/\D/g, "");
  if (!phone) return null;
  const where = (location.hash || "#/").replace(/^#/, "");
  const text = `Ассаляму алейкум! Пишу по приложению TanWin (версия ${APP_VERSION}, экран ${where}).\n${extra || "Нашёл(ла) ошибку: "}`;
  return `https://wa.me/${phone}?text=${encodeURIComponent(text)}`;
}
