// Обращение к ученику: на «вы» или на «ты», мужской или женский род.
// Все тексты приложения написаны на «вы»; при выборе «ты» они переводятся на лету (см. append() в ui.js).
// Переводятся только слова из словаря ниже — незнакомое слово остаётся как есть.
// Новое обращение на «вы» в тексте? Добавьте слово в словарь; `node tools/speech-check.mjs` покажет, чего не хватает.
import { store } from "./store.js";

export const isTy = () => store.get().profile.form === "ty";
export const gender = () => store.get().profile.gender || "";
/** Слово по роду ученика: g("Прочитал", "Прочитала"). Если род не указан — третий вариант (по умолчанию мужской). */
export const g = (m, f, none = m) => (gender() === "f" ? f : gender() === "m" ? m : none);

// Повелительное наклонение: «нажмите» → «нажми» (отбрасываем «те»), «не пугайтесь» → «не пугайся».
const IMPERATIVE = `нажмите сохраняйте задайте ставьте прочитайте послушайте повторяйте нажимайте читайте слушайте смотрите проверьте сравните выберите следите
  посмотрите повторите откройте попробуйте спешите найдите путайте отличайте сохраните пройдите напишите запишите ищите обновите
  проверяйте считайте добавляйте зажмите поставьте дайте скажите сожмите держите соберите соедините сообщите разрешите представьте
  дышите раскатывайте заменяйте сделайте запомните покажите установите продолжайте загрузите удерживайте листайте сдайте узнайте
  перескочите упомяните укажите выбирайте начните вернитесь научитесь пугайтесь задержитесь останавливайтесь остановитесь`.split(/\s+/);
const imperative = (w) => (w.endsWith("тесь") ? w.slice(0, -4) + (w.at(-5) === "й" ? "ся" : "сь") : w.slice(0, -2));

const WORDS = {
  ...Object.fromEntries(IMPERATIVE.map((w) => [w, imperative(w)])),
  вы: "ты", вас: "тебя", вам: "тебе", вами: "тобой",
  ваш: "твой", ваша: "твоя", ваше: "твоё", ваши: "твои", вашего: "твоего", вашей: "твоей", вашему: "твоему", вашим: "твоим", ваших: "твоих", вашу: "твою", вашем: "твоём",
  // настоящее и будущее время
  услышите: "услышишь", начинаете: "начинаешь", знаете: "знаешь", читаете: "читаешь", слышите: "слышишь", хотите: "хочешь", увидите: "увидишь",
  занимаетесь: "занимаешься", умеете: "умеешь", загибаете: "загибаешь", греете: "греешь", справитесь: "справишься", ответите: "ответишь",
  идёте: "идёшь", будете: "будешь", пройдёте: "пройдёшь", ошибётесь: "ошибёшься", смените: "сменишь", узнаёте: "узнаёшь", можете: "можешь", видите: "видишь", находитесь: "находишься",
};
// Прошедшее время и краткие прилагательные после «вы» зависят от рода: «вы прошли» → «ты прошёл / прошла».
const PAST = {
  слышали: ["слышал", "слышала"], складывали: ["складывал", "складывала"], научились: ["научился", "научилась"], прочитали: ["прочитал", "прочитала"],
  вернулись: ["вернулся", "вернулась"], прошли: ["прошёл", "прошла"], ошибались: ["ошибался", "ошибалась"], готовы: ["готов", "готова"],
};
const PAST_RE = new RegExp(`([Вв]ы(?: наверняка| уже)? )(${Object.keys(PAST).join("|")})`, "g");
// Здесь «вы» — не обращение к ученику: аят и благодарность жертвователям.
const KEEP = ["Вам — ваша религия", "да воздаст вам Аллах"];
const MAYBE = /те(?:сь)?(?![а-яё])|[Вв]ы(?![а-яё])|[Вв]а[смш]|готовы|остановились|Нашли/;

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

/** Переводит текст с «вы» на «ты», если ученик выбрал такое обращение. */
export function you(text) {
  if (typeof text !== "string" || !isTy() || !MAYBE.test(text)) return text;
  for (const k of KEEP) if (text.includes(k)) return text.split(k).map(you).join(k);
  const f = gender() === "f" ? 1 : 0;
  return text
    .replace(PAST_RE, (m, a, v) => a + PAST[v][f])
    .replace(/где остановились/g, f ? "где остановилась" : "где остановился")
    .replace(/((?:рочитайте|читаете)(?: его| её)?(?: вслух)?) сами/g, (m, a) => `${a} ${f ? "сама" : "сам"}`)
    .replace(/Нашли ошибку/g, f ? "Нашла ошибку" : "Нашёл ошибку")
    .replace(/[А-Яа-яЁё]+/g, (w, at, all) => {
      if (all[at - 1] === "«" && all[at + w.length] === "»") return w; // слово в кавычках — пример, а не обращение
      const low = w.toLowerCase();
      const t = Object.hasOwn(WORDS, low) ? WORDS[low] : null;
      return t ? (w === low ? t : cap(t)) : w;
    });
}

/** Слова, которые словарь умеет переводить, — для проверки tools/speech-check.mjs. */
export const KNOWN = new Set([...Object.keys(WORDS), ...Object.keys(PAST)]);
