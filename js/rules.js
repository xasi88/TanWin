/** Разбирает компактную разметку «[код текст]» в список фрагментов [текст, код|""]. */
export function parseMarkup(s) {
  const out = [];
  const re = /\[([a-zA-Z])([^\]]*)\]/g;
  let i = 0, m;
  while ((m = re.exec(s))) {
    if (m.index > i) out.push([s.slice(i, m.index), ""]);
    out.push([m[2], m[1]]);
    i = re.lastIndex;
  }
  if (i < s.length) out.push([s.slice(i), ""]);
  return out;
}
export const plain = (s) => s.replace(/\[[a-zA-Z]/g, "").replace(/\]/g, "");
